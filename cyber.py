SPEECH_LANG = {"en": "en-US", "bn": "bn-BD", "bnl": "bn-BD"}


def explain(result, lang="en"):
    t = TEXTS[lang]
    verdict = result["verdict"]
    parts = [t["headline"][verdict]]

    if verdict in ("suspicious", "legit", "promo") and verdict == result["text_verdict"]:
        top = max(result["probabilities"].values())
        parts.append(t["sure_high"] if top >= 0.8 else t["sure_mid"] if top >= 0.6 else t["sure_low"])

    levels = [link["level"] for link in result["links"]]
    if result["threat_list"]["flagged"]:
        parts.append(t["threat"])
    elif "risky" in levels:
        parts.append(t["link_risky"])
    elif "check" in levels:
        parts.append(t["link_check"])
    if result["payment_notice"]:
        parts.append(t["notice"])
    if result["dial_codes"]:
        parts.append(t["dial"])
    parts.append(t["advice"][verdict])

    text = " ".join(parts)
    # Banglish has no voice of its own: speak the Bangla version instead.
    speech_text = explain(result, "bn")["text"] if lang == "bnl" else text
    return {"lang": lang, "text": text, "speech_text": speech_text,
            "speech_lang": SPEECH_LANG[lang]}